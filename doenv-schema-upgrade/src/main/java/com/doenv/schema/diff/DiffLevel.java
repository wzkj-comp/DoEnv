package com.doenv.schema.diff;

/**
 * 差异的处置档位。
 *
 * <p>档位决定界面上能不能勾、能不能执行 —— 这是整套工具最重要的安全边界。
 */
public enum DiffLevel {

    /** 默认勾选，可直接执行。纯元数据操作或已验证安全 */
    AUTO,

    /** 默认不勾。需要前置探测（重复值/NULL 计数/表行数）通过后才允许勾选 */
    CONFIRM,

    /** 界面上物理没有执行按钮，只出 SQL 文本供人工处理 */
    MANUAL,

    /** 只读折叠展示，永远不生成 DDL（现场多出的对象走这一档） */
    INFO
}
