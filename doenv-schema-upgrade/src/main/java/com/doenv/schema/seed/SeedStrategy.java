package com.doenv.schema.seed;

/**
 * 配置数据的下发策略。
 *
 * <p>全局前提：<b>任何策略都不删除现场多出的行</b>（{@link #FULL_OVERWRITE} 除外）。
 * 全库外键约束数为 0，所有引用都是逻辑外键 —— 删父行不报错，只让功能悄悄少一块。
 */
public enum SeedStrategy {

    /**
     * 全量覆盖：按 deletePredicate 删掉基准来源的旧行再整体重灌。
     * 只适用于「全仓 0 条运行时写路径 + 0 个引用方」的表，实测整个基准里只有一张够格。
     */
    FULL_OVERWRITE,

    /**
     * 按稳定键 UPSERT，且 SET 子句里绝不出现冻结列。
     * 匹配不上的行 INSERT；现场多出的行原样保留。
     */
    MERGE_FREEZE,

    /**
     * 只补缺行。匹配上的行一个字段都不改。
     * 适用于整表都是现场态（后端按父键整组 delete+insert 重建，或用户可自由增删改）。
     */
    INSERT_ONLY,

    /**
     * 只查表和列，数据一行都不下发。
     * 用于敏感数据（含明文口令/账号）、演示数据、每用户偏好，以及
     * 基准侧数据本身就不该分发的表。
     */
    STRUCTURE_ONLY,

    /**
     * 整表重建：清空后按基准全量重灌。
     *
     * <p>用于「基准与现场本该逐行强一致、连 id 都一致」的元数据表
     * （实体/记录类型及其属性定义）。这类表的数据全靠增量 SQL 维护 ——
     * 2026 一年里 6798 条数据操作有 5300+ 条打在这四张表上，
     * 逐行 UPDATE 对齐既慢又容易被不唯一的稳定键卡住，重建反而干净。
     *
     * <p>两个配套机制：
     * <ul>
     *   <li>{@code rebuildCheckColumns} —— 先比对，真有差异才重建，一致则零操作</li>
     *   <li>{@code preserve} —— 运行时统计列（如 count）先取出、重建后回填</li>
     * </ul>
     *
     * <p><b>现场独有的行会被删掉</b>，这正是「严格以基准为准」的语义。
     */
    REBUILD
}
